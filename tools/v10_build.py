#!/usr/bin/env python3
"""Bundle V10/src/*.py (+ generated value-model weights) into V10/v10.py.

    python3 tools/v10_build.py          # build + syntax check + link into the generator
"""
import glob, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import value_dataset as vd

SRC = os.path.join(ROOT, 'V10', 'src')
OUT = os.environ.get('V10_OUT') or os.path.join(ROOT, 'V10', 'v10.py')
MODEL = os.environ.get('V10_MODEL') or os.path.join(ROOT, 'data', 'prod', 'value_mono.json')
GEN = '/home/ubuntu/leek-wars-generator'


def r6(v):
    if isinstance(v, list):
        return '[' + ', '.join(r6(x) for x in v) + ']'
    return repr(round(v, 6))


def value_data():
    m = json.load(open(MODEL))
    assert m['names'] == vd.NAMES, 'value model / feature layout mismatch'
    (W1, b1), (W2, b2), (W3, b3) = m['layers']
    names = m['names']
    return '\n'.join([
        '# ---- 05_value_data: GENERATED by tools/v10_build.py from data/prod/value_mono.json',
        'VN_GROUPS = %r' % vd.GROUPS,
        'VN_GSCALE = %s' % r6([vd.GSCALE.get(g, 100.0) for g in vd.GROUPS]),
        'VN_GROUP_OF = %r' % {t: g for t, g in vd.GROUP.items()},
        'VN_MU = %s' % r6(m['mu']), 'VN_SD = %s' % r6(m['sd']),
        'VN_CI = %r' % [names.index(n) for n in m['ctx']],
        'VN_MI = %r' % [names.index(n) for n in m['mono']],
        'VN_SIGN = %s' % r6(m['sign']),
        'VN_W1 = %s' % r6(W1), 'VN_B1 = %s' % r6(b1),
        'VN_W2 = %s' % r6(W2), 'VN_B2 = %s' % r6(b2),
        'VN_W3 = %s' % r6(W3), 'VN_B3 = %s' % r6(b3), ''])


def main():
    parts = ['# V10 — GENERATED by tools/v10_build.py from V10/src (do not edit this file)\n']
    files = sorted(glob.glob(os.path.join(SRC, '*.py')))
    inserted = False
    for f in files:
        name = os.path.basename(f)
        if not inserted and name > '05':
            parts.append(value_data()); inserted = True
        parts.append(open(f).read())
    src = '\n\n'.join(parts)
    compile(src, OUT, 'exec')
    open(OUT, 'w').write(src)
    link = os.path.join(GEN, 'V10')
    if not os.path.islink(link):
        os.symlink(os.path.join(ROOT, 'V10'), link)
    print('wrote %s (%d lines, %d bytes)' % (OUT, src.count('\n'), len(src)))


if __name__ == '__main__':
    main()
